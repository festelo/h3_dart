#!/bin/bash

set -euo pipefail

# Absolute path to script's directory
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$SCRIPT_DIR/.."

# Clean build dir
rm -rf build
mkdir build
cd build

# Number of cores for parallel build
NUM_CORES=$(sysctl -n hw.ncpu)

##########
# iOS
##########

mkdir ios
cd ios
cmake ../.. \
    -DCMAKE_SYSTEM_NAME=iOS \
    -DCMAKE_OSX_ARCHITECTURES=arm64 \
    -DCMAKE_OSX_SYSROOT=$(xcodebuild -version -sdk iphoneos Path) \
    -DCMAKE_OSX_DEPLOYMENT_TARGET=12.0 \
    -DCMAKE_INSTALL_PREFIX=$(pwd)/install \
    -DBUILD_SHARED_LIBS=OFF
make -j"$NUM_CORES"
make install
cd ..

##########
# iOS Simulator
##########

mkdir ios-simulator
cd ios-simulator
cmake ../.. \
    -DCMAKE_SYSTEM_NAME=iOS \
    -DCMAKE_OSX_ARCHITECTURES="x86_64;arm64" \
    -DCMAKE_OSX_SYSROOT=$(xcodebuild -version -sdk iphonesimulator Path) \
    -DCMAKE_OSX_DEPLOYMENT_TARGET=12.0 \
    -DCMAKE_INSTALL_PREFIX=$(pwd)/install \
    -DBUILD_SHARED_LIBS=OFF
make -j"$NUM_CORES"
make install
cd ..

##########
# macOS
##########

mkdir macos
cd macos
cmake ../.. \
    -DCMAKE_SYSTEM_NAME=Darwin \
    -DCMAKE_OSX_ARCHITECTURES="x86_64;arm64" \
    -DCMAKE_OSX_SYSROOT=$(xcodebuild -version -sdk macosx Path) \
    -DCMAKE_OSX_DEPLOYMENT_TARGET=10.13 \
    -DCMAKE_INSTALL_PREFIX=$(pwd)/install \
    -DBUILD_SHARED_LIBS=OFF
make -j"$NUM_CORES"
make install
cd ..

##########
# Create XCFramework
##########

xcodebuild -create-xcframework \
    -library ios/install/lib/libh3.a \
    -headers ios/install/include \
    -library ios-simulator/install/lib/libh3.a \
    -headers ios-simulator/install/include \
    -library macos/install/lib/libh3.a \
    -headers macos/install/include \
    -output h3.xcframework

##########
# Keep H3 symbols in macOS apps that link pods statically
##########

# h3_flutter finds H3 functions with DynamicLibrary.process(). When pods are
# linked statically, the linker drops every object of libh3.a that the app
# does not reference. This file references all H3 functions, and its
# Objective-C class makes the -ObjC flag set by CocoaPods load it.
symbols=$(grep -v '#define' macos/install/include/h3api.h \
    | grep -o 'H3_EXPORT([A-Za-z0-9_]*)' \
    | sed 's/^H3_EXPORT(\(.*\))$/\1/' \
    | sort -u)
{
    echo '// Generated by bindings/scripts/build_darwin_static_lib.sh, do not edit.'
    echo '#import <Foundation/Foundation.h>'
    echo
    for symbol in $symbols; do
        echo "extern void $symbol(void);"
    done
    echo
    echo '__attribute__((used)) static void *const h3_flutter_symbols[] = {'
    for symbol in $symbols; do
        echo "    (void *)&$symbol,"
    done
    echo '};'
    echo
    echo '@interface H3FlutterSymbols : NSObject'
    echo '@end'
    echo
    echo '@implementation H3FlutterSymbols'
    echo '@end'
} > h3_flutter_symbols.m
cd ..

##########
# Copy output
##########

rm -rf ../darwin/Libs/h3.xcframework
mkdir -p ../darwin/Libs
cp -r build/h3.xcframework ../darwin/Libs/
cp build/h3_flutter_symbols.m ../darwin/Libs/

# Clean build folder
rm -rf build

echo "✅ The XCFramework was built successfully: darwin/Libs/h3.xcframework"